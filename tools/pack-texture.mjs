// Generates src/character-texture.js from assets/character-chibi.png.
// The image is inlined as a data URL so WebGL can upload it without the
// file:// canvas-tainting problem.
//
// Usage: node tools/pack-texture.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const png = readFileSync(join(root, "assets", "character-chibi.png"));
const dataUrl = `data:image/png;base64,${png.toString("base64")}`;
const out = `// Generated by tools/pack-texture.mjs — do not edit by hand.\nwindow.CHARACTER_TEXTURE = "${dataUrl}";\n`;
writeFileSync(join(root, "src", "character-texture.js"), out, "utf8");
console.log(`character-texture.js written: ${Math.round(out.length / 1024)} KB`);
